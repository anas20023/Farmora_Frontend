/**
 * Returns static listings matching server filters or initial static state
 */
export async function getMarketplaceListings(): Promise<{
  listings: ProductListing[];
  stats: {
    totalListings: number;
    inStockCount: number;
    preOrderCount: number;
    verifiedFarmsCount: number;
    totalTonnageAvailable: number;
  };
}> {
  const listings = MOCK_PRODUCT_LISTINGS;
  const inStockCount = listings.filter((l) => l.listingType === "IN_STOCK").length;
  const preOrderCount = listings.filter((l) => l.listingType === "PRE_ORDER").length;
  const uniqueFarms = new Set(listings.map((l) => l.farmId)).size;
  const totalKg = listings.reduce((acc, curr) => acc + curr.availableQuantity, 0);

  return {
    listings,
    stats: {
      totalListings: listings.length,
      inStockCount,
      preOrderCount,
      verifiedFarmsCount: uniqueFarms,
      totalTonnageAvailable: Math.round(totalKg / 1000),
    },
  };
}
